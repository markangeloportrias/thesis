-- Bring an older copy of this table forward without requiring a destructive
-- reset. New rows always carry the year that belongs to their selected block.
ALTER TABLE public.student_block_assignments
  ADD COLUMN IF NOT EXISTS school_year_id bigint;

UPDATE public.student_block_assignments AS a
SET school_year_id = b.school_year_id
FROM public.student_blocks AS b
WHERE b.id = a.block_id
  AND a.school_year_id IS NULL;

DO $$
DECLARE
  missing_school_years bigint;
BEGIN
  SELECT COUNT(*)
  INTO missing_school_years
  FROM public.student_block_assignments
  WHERE school_year_id IS NULL;

  IF missing_school_years > 0 THEN
    RAISE EXCEPTION
      'Cannot migrate student_block_assignments: % row(s) have no matching school year',
      missing_school_years;
  END IF;
END;
$$;

ALTER TABLE public.student_block_assignments
  ALTER COLUMN school_year_id SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.student_block_assignments'::regclass
      AND conname = 'fk_assignment_school_year'
  ) THEN
    EXECUTE 'ALTER TABLE public.student_block_assignments
      ADD CONSTRAINT fk_assignment_school_year
      FOREIGN KEY (school_year_id) REFERENCES public.school_years(id)
      ON UPDATE CASCADE ON DELETE RESTRICT';
  END IF;
END;
$$;

ALTER TABLE public.student_block_assignments
  DROP CONSTRAINT IF EXISTS uq_student_block;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'public.student_block_assignments'::regclass
      AND conname = 'uq_student_school_year'
  ) THEN
    EXECUTE 'ALTER TABLE public.student_block_assignments
      ADD CONSTRAINT uq_student_school_year UNIQUE (student_id, school_year_id)';
  END IF;
END;
$$;

