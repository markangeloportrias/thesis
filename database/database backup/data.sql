CREATE OR REPLACE VIEW public.v_student_case_summary
WITH (security_invoker = true)
AS
SELECT
  s.student_id,
  s.student_name,
  COUNT(c.id) AS total_cases,
  COALESCE(SUM(
    CASE
      WHEN c.checked_by IS NOT NULL AND btrim(c.checked_by) <> '' THEN 1
      ELSE 0
    END
  ), 0) AS verified_cases,
  string_agg(DISTINCT c.procedure_name, ', ' ORDER BY c.procedure_name) AS procedures
FROM public.students AS s
LEFT JOIN public.case_records AS c ON c.student_id = s.student_id
GROUP BY s.student_id, s.student_name;

CREATE OR REPLACE VIEW public.v_school_year_procedure_summary
WITH (security_invoker = true)
AS
SELECT
  c.academic_year AS school_year,
  c.procedure_key,
  c.procedure_name,
  COUNT(*) AS total_records,
  COUNT(DISTINCT c.student_id) AS total_students,
  COALESCE(SUM(
    CASE
      WHEN c.checked_by IS NOT NULL AND btrim(c.checked_by) <> '' THEN 1
      ELSE 0
    END
  ), 0) AS verified_records
FROM public.case_records AS c
WHERE c.academic_year IS NOT NULL
  AND btrim(c.academic_year) <> ''
GROUP BY c.academic_year, c.procedure_key, c.procedure_name;

