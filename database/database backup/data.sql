-- Supabase/PostgreSQL schema for the thesis portal.
-- Run this file in the Supabase SQL editor (or as a migration).
--
-- The portal currently authenticates through its API rather than Supabase Auth.
-- RLS is therefore enabled below with no public write policies: use a trusted
-- server connection/service-role client for the API and never expose that key
-- in browser code.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
-- Supabase installs extensions in `extensions`; public is included for
-- PostgreSQL installations that place pgcrypto there instead.
SET LOCAL search_path TO public, extensions;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, extensions
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS public.admins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pin_number varchar(255) NOT NULL,
  must_change_pin boolean NOT NULL DEFAULT false,
  archived_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.admins
  ADD COLUMN IF NOT EXISTS must_change_pin boolean NOT NULL DEFAULT false;

-- Migration bootstrap administrator. Store the PIN as a bcrypt hash rather
-- than plaintext; change it immediately after the first administrator login.
-- The seed is idempotent. Replace/remove this block if your deployment has a
-- separate, controlled administrator provisioning process.
DO $$
BEGIN
  -- Supabase commonly keeps extensions in the `extensions` schema, while
  -- self-hosted PostgreSQL may keep pgcrypto in `public`; include both.
  PERFORM set_config('search_path', 'public, extensions', true);

  IF NOT EXISTS (
    SELECT 1 FROM public.admins WHERE archived_at IS NULL
  ) THEN
    INSERT INTO public.admins (pin_number, must_change_pin)
    VALUES (crypt('123456', gen_salt('bf', 12)), true);
  END IF;
END;
$$;

